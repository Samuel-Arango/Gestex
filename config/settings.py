def _env_bool(nombre, por_defecto=False):
    """Lee una variable de entorno como booleano (1, true, yes u on). Si no existe, usa el valor por defecto."""
    valor = os.environ.get(nombre)
    if valor is None:
        return por_defecto
    return valor.strip().lower() in ('1', 'true', 'yes', 'on')


